export function getLocalizedCountryName(key: string, locale: string): string {
  const entry = LOCALIZED_COUNTRY_NAMES[key];
  if (entry) return entry[locale] ?? entry['en'] ?? key;
  // Fallback for any key added after table generation
  const iso = COUNTRY_ISO_CODES[key];
  if (!iso) return key;
  try {
    const bcp47 = { no: 'nb', en: 'en-US', fr: 'fr-FR', es: 'es-ES', de: 'de-DE' }[locale] ?? locale;
    return new Intl.DisplayNames([bcp47], { type: 'region' }).of(iso) ?? key;
  } catch { return key; }
}

